def build(catalog, cases):
    lookup = {r["entity_key"]: r for r in catalog}
    if set(VARIANTS) != set(TARGETS) or set(VARIANTS) != {r["id"] for r in cases}:
        raise ValueError("Family set mismatch")
    seen = set()
    result = []
    for case in cases:
        targets = TARGETS[case["id"]]
        if not targets or any(k not in lookup for k in targets):
            raise ValueError("Unknown target")
        variants = [case["query"], *VARIANTS[case["id"]]]
        for number, query in enumerate(variants):
            key = normalize(query)
            if key in seen:
                raise ValueError("Duplicate query")
            seen.add(key)
            if any(normalize(lookup[t]["title"]) in key for t in targets):
                raise ValueError("A full target title is copied in a request")
            result.append(
                {
                    "id": f"{case['id']}-{number}",
                    "family": case["family"],
                    "original_split": case["split"],
                    "query": query,
                    "known_targets": targets,
                    "source": "assistant_authored_provisional",
                    "human_verified": False,
                }
            )
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--catalog", type=Path, required=True)
    p.add_argument("--queries", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    a = p.parse_args()
    if a.output.exists():
        raise ValueError("Output already exists")
    _, manifest, catalog = load_bundle(a.catalog)
    queries = build(catalog, json.loads(a.queries.read_text())["queries"])
    atomic_json(
        a.output,
        {
            "schema_version": 1,
            "catalog_sha256": manifest["catalog_sha256"],
            "source_queries_sha256": sha256(a.queries),
            "queries": queries,
            "limitations": "Assistant-authored paraphrases and expected links, no independent ratings; known targets form only a partial list of relevant material. Original families and some targets were used previously.",
        },
    )
    print(f"Created {len(queries)} queries in {len(VARIANTS)} topic families")


if __name__ == "__main__":
    main()
