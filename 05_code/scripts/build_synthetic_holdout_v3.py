def textnorm(text):
    return " ".join(re.findall(r"[а-яa-z0-9]+", text.casefold().replace("ё", "е")))


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--output", type=Path, required=True)
    a = p.parse_args()
    a.output.mkdir(parents=True, exist_ok=False)
    order = list(range(len(TASKS)))
    random.Random(73421).shuffle(order)
    test = set(order[:10])
    assert len(test) == 10
    old = json.loads(Path("artifacts/relevance_v1/training/synthetic_queries.json").read_text())
    oldqueries = {textnorm(x["query"]) for x in old}
    oldcases = json.loads(Path("evaluation/ensemble_cases_v2.json").read_text())["queries"]
    oldqueries |= {textnorm(x["query"]) for x in oldcases if x["split"] == "train"}
    manifest = {
        "schema_version": 1,
        "protocol": "Family-disjoint, separate catalog and index per split; manual task specification; labels are separate from indexed documents; test frozen before tuning, never used for weight selection. No human judgments. Same pretrained model may have unknown pretraining overlap.",
        "seed": 73421,
        "ranker_sha256": sha256(Path("artifacts/relevance_v1/training/ranker.cbm")),
        "test_status": "sealed_not_evaluated",
        "hashes": {},
        "counts": {},
    }
    allqueries = {}
    for split in ["validation", "test"]:
        docs = []
        cases = []
        labels = []
        for n, (topic, title, description, wrong, q1, q2) in enumerate(TASKS):
            if (n in test) != (split == "test"):
                continue
            family = f"task-{n:02d}"
            positive = []
            for kind in ["article", "course"]:
                key = (
                    kind
                    + ":"
                    + hashlib.sha256(f"v3:{split}:{family}:{kind}".encode()).hexdigest()[:24]
                )
                docs.append(item(key, title, description, topic))
                positive.append(key)
            for kind in ["document", "webinar"]:
                key = (
                    kind
                    + ":"
                    + hashlib.sha256(f"v3:{split}:{family}:wrong:{kind}".encode()).hexdigest()[:24]
                )
                docs.append(
                    item(
                        key,
                        wrong,
                        "Учебный материал на другую задачу: " + wrong.lower() + ".",
                        topic,
                    )
                )
            for query in [q1, q2]:
                normal = textnorm(query)
                if normal in allqueries or normal in oldqueries:
                    raise ValueError("Query duplicated or overlaps prior train")
                allqueries[normal] = split
                qid = hashlib.sha256(f"{split}:{family}:{query}".encode()).hexdigest()[:24]
                cases.append({"id": qid, "family": family, "query": query})
                labels.append({"id": qid, "positive": positive})
        random.Random(73421).shuffle(docs)
        random.Random(42).shuffle(cases)
        catalog = a.output / split / "catalog" / "generation-synthetic"
        catalog.mkdir(parents=True)
        atomic_json(catalog / "catalog.json", docs)
        digest = sha256(catalog / "catalog.json")
        atomic_json(catalog / "suggestions.json", build_index(docs, digest))
        atomic_json(
            catalog / "manifest.json",
            {
                "catalog_sha256": digest,
                "semantic": None,
                "suggestions": {"sha256": sha256(catalog / "suggestions.json")},
                "fictional": True,
            },
        )
        atomic_json(catalog.parent / "CURRENT.json", {"generation": catalog.name})
        for filename, data in [("queries.jsonl", cases), ("labels.jsonl", labels)]:
            target = a.output / split / filename
            target.write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in data))
            target.chmod(0o600)
        for target in [
            a.output / split / "queries.jsonl",
            a.output / split / "labels.jsonl",
            catalog / "catalog.json",
            catalog / "manifest.json",
            catalog / "suggestions.json",
            catalog.parent / "CURRENT.json",
        ]:
            manifest["hashes"][str(target.relative_to(a.output))] = sha256(target)
        manifest["counts"][split] = {
            "families": len(cases) // 2,
            "queries": len(cases),
            "documents": len(docs),
        }
    atomic_json(a.output / "manifest.json", manifest)
    print(json.dumps(manifest["counts"], ensure_ascii=False))


if __name__ == "__main__":
    main()
